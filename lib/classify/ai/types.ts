/**
 * שכבת ה-AI של הסיווג.
 *
 * ─── למה יש כאן ממשק ולא קריאה למודל ───
 *
 * ברגע הכתיבה, 98.5% מהתנועות מסווגות בכללים דטרמיניסטיים, והשאר הן שורות
 * שהמידע פשוט לא נמצא בהן ("הוראת קבע"). כלומר: אין היום עבודה למודל.
 * לחבר מודל עכשיו היה אומר לשלם, לחכות לרשת, ולקבל ניחושים — בשביל אפס
 * שיפור מדיד.
 *
 * מה שכן יידרש: בכל חודש יופיעו בתי עסק חדשים שאיש לא כתב להם כלל. השכבה
 * הזו קיימת בשבילם. היא מוגדרת עכשיו, כשהראש נקי, ולא בלחץ של "יש 40
 * תנועות לא מסווגות והמשתמש מחכה".
 *
 * ─── מה עובר החוצה ───
 *
 * שם בית העסק בלבד. לא סכום, לא תאריך, לא מספר כרטיס, לא יתרה. ההחלטה
 * הזו לא נובעת מזהירות כללית אלא מכך שאין בה מחיר: הקטגוריה של הספק
 * וסוג התנועה כבר הוכרעו דטרמיניסטית *לפני* השלב הזה, כך שהמודל ממילא
 * רואה רק מקרים שבהם המחרוזת היא כל מה שיש.
 *
 * זו גם הסיבה שהממשק מקבל `string[]` ולא `Transaction[]`. טיפוס צר הוא
 * הדרך הזולה ביותר לאכוף מדיניות פרטיות: אי אפשר להדליף שדה שלא הועבר.
 */

/** תשובת המסווג על בית עסק אחד. */
export type AiVerdict = {
  merchant: string;
  /** slug מתוך הרשימה המותרת, או null כשהמודל לא יודע. */
  slug: string | null;
  /** 0..1. מתחת לסף שנקבע בהרצה — התשובה נזרקת. */
  confidence: number;
  /** נימוק קצר. נשמר בלוג ובדוחות, לא במסד. */
  reason?: string;
};

export interface CategoryClassifier {
  readonly name: string;
  /**
   * @param merchants שמות בתי עסק מנורמלים, ייחודיים.
   * @param allowedSlugs הרשימה הסגורה שממנה מותר לבחור.
   */
  classify(merchants: string[], allowedSlugs: string[]): Promise<AiVerdict[]>;
}

/**
 * ברירת המחדל: לא מסווג כלום.
 *
 * << לא זורק שגיאה בכוונה. "אין מסווג מוגדר" הוא מצב תקין ולא תקלה —
 *    הצינור ממשיך, התנועות נשארות בלי קטגוריה, והמשתמש יכריע בעצמו.
 *    מסווג שזורק היה הופך תכונה אופציונלית לתלות חובה.
 */
export class NullClassifier implements CategoryClassifier {
  readonly name = "none";
  async classify(): Promise<AiVerdict[]> {
    return [];
  }
}
