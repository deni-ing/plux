/** קטגוריית MAX → slug אצלנו. אין יותר null מכוון — ראו "שונות" למעלה. */
export const MAX_CATEGORY_MAP: Record<string, string | null> = {
  "מזון וצריכה": "food.groceries",
  "מסעדות, קפה וברים": "food.restaurants",
  אופנה: "shopping.clothing",
  "עיצוב הבית": "shopping.home",
  "חשמל ומחשבים": "shopping.electronics",
  "רפואה ובתי מרקחת": "health",
  "עירייה וממשלה": "financial.taxes",
  "דלק, חשמל וגז": "fuel_utilities",
  "פנאי, בידור וספורט": "leisure",
  "העברת כספים": "transfers_out.bit",
  "טיסות ותיירות": "travel",
  שונות: "misc",
};

/**
 * << מ-26.08: ריקה בכוונה. עד אז סימנה קטגוריות MAX ש"בערך נכונות"
 *    ודורשות כלל בית-עסק כדי להיות מדויקות. עכשיו קטגוריית MAX *היא*
 *    היעד המדויק, אז אין יותר "בערך" להצביע עליו — נשארת קיימת (ולא
 *    נמחקת) רק כדי לא לשבור את מי שמייבא אותה.
 */
export const MAX_COARSE_CATEGORIES = new Set<string>([]);

/** נרמול קל: MAX לא עקבית ברווחים בקצוות. */
export function mapMaxCategory(raw: string | null | undefined): {
  slug: string | null;
  known: boolean;
  coarse: boolean;
} {
  const key = (raw ?? "").trim();
  if (!key) return { slug: null, known: false, coarse: false };

  const known = Object.prototype.hasOwnProperty.call(MAX_CATEGORY_MAP, key);
  return {
    slug: known ? MAX_CATEGORY_MAP[key] : null,
    known,
    coarse: MAX_COARSE_CATEGORIES.has(key),
  };
}
